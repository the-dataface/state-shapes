import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const regionsPath = join(root, 'scripts', 'generated', 'world-regions.json');
const outputPath = join(root, 'src', 'world.generated.ts');

const regions = JSON.parse(await readFile(regionsPath, 'utf8'));
const entries = Object.entries(regions).sort(([a], [b]) => a.localeCompare(b));

const isoCodes = entries.map(([code]) => `'${code}'`);
const countrySlugs = entries.map(([, { slug }]) => `'${slug}'`);

const worldCountriesBody = entries
  .map(([code, { slug, name }]) => `  ${code}: { slug: '${slug}', name: ${JSON.stringify(name)} },`)
  .join('\n');

const contents = `// Generated by scripts/generate-world-ts.mjs — do not edit manually

export type IsoCode = ${isoCodes.join(' | ')};

export type CountrySlug = ${countrySlugs.join(' | ')};

export type WorldRegion = {
  slug: CountrySlug;
  name: string;
};

export const WORLD_COUNTRIES: Record<IsoCode, WorldRegion> = {
${worldCountriesBody}
};
`;

await writeFile(outputPath, contents, 'utf8');
console.log(`Generated src/world.generated.ts with ${entries.length} countries`);
